"""Writes crates/isa/loongarch/tests/golden.txt: LLVM's text (llvm-objdump
-d) for encodings of each LoongArch instruction hexcavator's decoder knows (up
to four of each, their operand bits random), and for random words, on
LA32 and LA64; `<unknown>` where LLVM decodes nothing.

Usage: python oracle.py <LLVM bin directory> <crates/isa/loongarch>

The encodings come from the crate's tables.rs (each instruction's fixed
bits); the words are assembled with `.word` (llvm-mc) and disassembled at
their addresses. Seeded: the same tables give the same file.
"""

import os
import random
import re
import subprocess
import sys
import tempfile

PER_INSTRUCTION = 4
RANDOM_WORDS = 3000

# Words random ones rarely are: `ud` (and `amswap.w` beside it), and each
# alias, with registers and offsets at their edges.
EDGES = [
    0x38600421,  # ud 1
    0x38607FFF,  # rk 31: amswap.w (LA64's alone)
    0x38600400,  # ud 0
    0x38600422,  # amswap.w $tp, $ra, $ra
    0x386014C4,  # amswap.w $a0, $a1, $a2 (LA64's alone)
    0x03400000,  # nop
    0x03400001,  # andi $ra, $zero, 0
    0x001500A4,  # move $a0, $a1
    0x00150004,  # move $a0, $zero
    0x4C000020,  # ret
    0x4C000080,  # jr $a0
    0x4C000000,  # jr $zero
    0x4C000420,  # jirl $zero, $ra, 4
    0x00006080,  # rdcntid.w $a0
    0x00006004,  # rdcntvl.w $a0
    0x00006404,  # rdcntvh.w $a0
    0x00006000,  # rdcntid.w $zero
    0x60000000,  # bltz $zero, 0
    0x60000080,  # bltz $a0
    0x60000004,  # bgtz $a0
    0x64000080,  # bgez $a0
    0x64000004,  # blez $a0
    0x64000000,  # blez $zero, 0
    0x63FFFC80,  # bltz $a0, -4
    0x53FFFFFF,  # b -4
    0x50000200,  # b, the furthest back
    0x57FFFDFF,  # bl, the furthest forward
    0x4BFFFC1F,  # bceqz $fcc0, -4
    0x48000100,  # bcnez $fcc0, 0
]


def encodings(crate):
    """Each instruction's (mask, value), from tables.rs."""
    src = open(os.path.join(crate, "src", "tables.rs"), encoding="utf-8").read()
    out = []
    for m in re.finditer(r"Inst \{ name: \"(\w+)\", size: 4, space: \d+, mask: (0x[0-9a-f]+), value: (0x[0-9a-f]+), ", src):
        out.append((int(m[2], 16), int(m[3], 16)))
    return out


def words(crate, rng):
    out = []
    for mask, value in encodings(crate):
        for _ in range(PER_INSTRUCTION):
            out.append((value | (rng.getrandbits(32) & ~mask)) & 0xFFFFFFFF)
    for _ in range(RANDOM_WORDS):
        out.append(rng.getrandbits(32))
    out += EDGES
    # (Each once, in order.)
    return list(dict.fromkeys(out))


def disassemble(llvm, triple, ws, tmp):
    asm = os.path.join(tmp, "in.s")
    obj = os.path.join(tmp, "in.o")
    with open(asm, "w") as f:
        f.write("\t.text\n")
        for w in ws:
            f.write(f"\t.word {w:#x}\n")
    subprocess.run(
        [os.path.join(llvm, "llvm-mc"), "-triple", triple, "-filetype=obj", asm, "-o", obj],
        check=True,
    )
    text = subprocess.run(
        [os.path.join(llvm, "llvm-objdump"), "-d", "--no-show-raw-insn", obj],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    out = {}
    for line in text.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s*(.*)$", line)
        if not m:
            continue
        rest = m[2].strip()
        # (A branch target's symbol: dropped.)
        rest = rest if rest.startswith("<") else re.sub(r"\s+<[^>]*>$", "", rest)
        out[int(m[1], 16)] = rest
    return out


def main():
    llvm, crate = sys.argv[1], sys.argv[2]
    rng = random.Random(20261121)
    ws = words(crate, rng)
    lines = [
        "# Generated by tools/loongarch/oracle.py: LLVM's text (llvm-objdump -d)",
        "# for encodings of each instruction and random words, at their addresses.",
        "# LA32 or LA64, word, address, then LLVM's text.",
    ]
    for base, triple in (("LA32", "loongarch32"), ("LA64", "loongarch64")):
        with tempfile.TemporaryDirectory() as tmp:
            got = disassemble(llvm, triple, ws, tmp)
        for k, w in enumerate(ws):
            at = 4 * k
            lines.append(f"{base} {w:08x} {at:x}\t{got.get(at, '<missing>')}")
    path = os.path.join(crate, "tests", "golden.txt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
