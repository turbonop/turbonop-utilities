"""Writes crates/isa/riscv/tests/golden.txt: LLVM's text (llvm-objdump -d)
for encodings of each RISC-V instruction hexcavator's decoder knows (up to four
of each, their operand bits random), and for random 16- and 32-bit words,
on RV32 and RV64, with the standard extensions hexcavator's
`Features::standard` turns on; `<unknown>` where LLVM decodes nothing.

Usage: python oracle.py <LLVM bin directory> <crates/isa/riscv>

The encodings come from the crate's tables.rs (each instruction's fixed
bits); the words are assembled with `.insn` (llvm-mc) and disassembled at
their addresses. Seeded: the same tables give the same file.
"""

import os
import random
import re
import subprocess
import sys
import tempfile

PER_INSTRUCTION = 4
RANDOM_WORDS = 3000


def standard_features(crate):
    """The STANDARD list of lib.rs."""
    src = open(os.path.join(crate, "src", "lib.rs"), encoding="utf-8").read()
    body = src[src.index("const STANDARD: &[&str] = &[") :]
    body = body[: body.index("];")]
    return re.findall(r'"([^"]+)"', body)


def encodings(crate):
    """Each instruction's (size, mask, value), from tables.rs."""
    src = open(os.path.join(crate, "src", "tables.rs"), encoding="utf-8").read()
    out = []
    for m in re.finditer(r"Inst \{ name: \"(\w+)\", size: (\d), space: \d+, mask: (0x[0-9a-f]+), value: (0x[0-9a-f]+), ", src):
        out.append((m[1], int(m[2]), int(m[3], 16), int(m[4], 16)))
    return out


def words(crate, rng):
    out = []
    for name, size, mask, value in encodings(crate):
        bits = 8 * size
        for _ in range(PER_INSTRUCTION):
            w = (value | (rng.getrandbits(bits) & ~mask)) & ((1 << bits) - 1)
            out.append((size, w))
    for _ in range(RANDOM_WORDS):
        # (Not a longer instruction's start: bits 4:2 all set.)
        w = rng.getrandbits(32) | 3
        if w & 0x1C != 0x1C:
            out.append((4, w))
        w = rng.getrandbits(16)
        if w & 3 != 3:
            out.append((2, w))
    # (Each once, in order.)
    seen = set()
    unique = []
    for s, w in out:
        if (s, w) not in seen:
            seen.add((s, w))
            unique.append((s, w))
    return unique


def disassemble(llvm, triple, mattr, ws, tmp):
    asm = os.path.join(tmp, "in.s")
    obj = os.path.join(tmp, "in.o")
    with open(asm, "w") as f:
        f.write("\t.text\n")
        for size, w in ws:
            f.write(f"\t.insn {size}, {w:#x}\n")
    subprocess.run(
        [os.path.join(llvm, "llvm-mc"), "-triple", triple, "-mattr=+c", "-filetype=obj", asm, "-o", obj],
        check=True,
    )
    text = subprocess.run(
        [os.path.join(llvm, "llvm-objdump"), "-d", "--no-show-raw-insn", f"--mattr={mattr}", obj],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    out = {}
    for line in text.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s*(.*)$", line)
        if not m:
            continue
        rest = m[2].strip()
        # (A branch target's symbol: dropped.)
        rest = rest if rest.startswith("<") else re.sub(r"\s+<[^>]*>$", "", rest)
        out[int(m[1], 16)] = rest
    return out


def main():
    llvm, crate = sys.argv[1], sys.argv[2]
    rng = random.Random(20261121)
    ws = words(crate, rng)
    feats = standard_features(crate)
    lines = [
        "# Generated by tools/riscv/oracle.py: LLVM's text (llvm-objdump -d) for",
        "# encodings of each instruction and random words, at their addresses.",
        "# XLEN, size in bytes, word, address, then LLVM's text.",
    ]
    for xlen, triple in (("RV32", "riscv32"), ("RV64", "riscv64")):
        mattr = ",".join("+" + f for f in feats)
        with tempfile.TemporaryDirectory() as tmp:
            got = disassemble(llvm, triple, mattr, ws, tmp)
        at = 0
        for size, w in ws:
            text = got.get(at, "<missing>")
            lines.append(f"{xlen} {size} {w:0{size * 2}x} {at:x}\t{text}")
            at += size
    path = os.path.join(crate, "tests", "golden.txt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
