#!/bin/sh
# Builds Intel XED and xedaccess, then runs it over turbonop-x86's sample
# encodings to make the access oracle's golden file:
#
#     tools/x86access/build.sh <scratch dir> <samples> > crates/isa/x86/tests/data/access.txt
#
# The samples come from
#
#     SAMPLES=<file> cargo test -p turbonop-x86 --test it generate_samples -- --ignored
#
# XED and mbuild are cloned into the scratch directory (outside the
# repository: a Linux file system builds faster than /mnt/c). Pass XED_REF
# to pin a commit.
set -eu
scratch=$1
samples=$2
here=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$scratch"
cd "$scratch"
[ -d xed ] || git clone -q https://github.com/intelxed/xed.git
[ -d mbuild ] || git clone -q https://github.com/intelxed/mbuild.git
if [ -n "${XED_REF:-}" ]; then
    git -C xed checkout -q "$XED_REF"
fi
kit=$(ls -d xed/kits/xed-install-base-* 2>/dev/null | head -n 1 || true)
if [ -z "$kit" ]; then
    (cd xed && python3 mfile.py --static -j "$(nproc)" install >&2)
    kit=$(ls -d xed/kits/xed-install-base-* | head -n 1)
fi
cc -O2 -o xedaccess "$here/xedaccess.c" -I"$kit/include" "$kit/lib/libxed.a"
echo "# Generated by tools/x86access/build.sh: Intel XED $(git -C xed log -1 --format=%h) on turbonop-x86's samples."
echo "# <mode> <hex> | <iclass> <length> | r=<registers read> | w=<written> | m=<memory r/w> | f=<flags read>/<written>/<undefined>"
./xedaccess < "$samples"
